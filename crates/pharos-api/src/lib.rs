//! Cap'n Proto schema crate for the pharos native API (spec 017, V173).
//!
//! Holds the generated bindings for `schema/pharos.capnp`, so the server and
//! the wasm UI share one wire definition, and the generated instrumentation
//! every served method goes through: serve a handler via
//! `server::<interface>::client`, which wraps it in `Instrumented<S>`
//! (research R4). capnpc's raw `Server` traits stay public, so
//! `tests/it_instrument/guard.rs` fails on any crate implementing one.

pub mod instrument;
pub mod labels;
pub mod redact;

pub use instrument::{register_metrics, set_trace_parent_hook, Connection, Denial};

// Generated by capnpc; these lints fire on its output, not on hand-written code.
#[allow(clippy::unwrap_used, clippy::match_single_binding)]
pub mod pharos_capnp {
    include!(concat!(env!("OUT_DIR"), "/pharos_capnp.rs"));
}

/// Per-interface `Handler` traits and their `Instrumented<S>` wrappers,
/// generated by `build/gen.rs`.
pub mod server {
    include!(concat!(env!("OUT_DIR"), "/instrumented.rs"));
}

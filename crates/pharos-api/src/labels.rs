//! Metric names and label values for the native API. Labels are a dashboard
//! contract: bounded, stable strings from `label()`, asserted distinct in
//! `tests/it_instrument/labels.rs` (017 §Observability).

/// `pharos_rpc_calls_total{interface,method,outcome}`.
pub const CALLS_TOTAL: &str = "pharos_rpc_calls_total";
/// `pharos_rpc_duration_seconds{interface,method}`.
pub const DURATION_SECONDS: &str = "pharos_rpc_duration_seconds";
/// `pharos_rpc_cancelled_total{interface,method}`: the caller dropped the call
/// or disconnected before it completed (HTTP's `http_client_aborted_total`).
pub const CANCELLED_TOTAL: &str = "pharos_rpc_cancelled_total";
/// `pharos_rpc_limit_total{limit}`: a call or connection refused at a cap
/// (FR-010). `limit` is the cap's fixed name, as the typed `Limit` carries it.
pub const LIMIT_TOTAL: &str = "pharos_rpc_limit_total";

/// One schema method, generated by `build/gen.rs`.
#[derive(Debug)]
pub struct MethodMeta {
    pub interface: &'static str,
    pub method: &'static str,
    /// `rpc.<interface>.<method>`.
    pub span: &'static str,
}

/// One schema interface and its methods, generated by `build/gen.rs`.
#[derive(Debug)]
pub struct InterfaceMeta {
    pub label: &'static str,
    pub methods: &'static [MethodMeta],
}

/// How a call ended. The `outcome` label of `pharos_rpc_calls_total`.
#[derive(Clone, Copy, Debug, PartialEq, Eq)]
pub enum Outcome {
    Ok,
    /// `Error.kind.notFound`.
    NotFound,
    /// `Error.kind.notPermitted`.
    NotPermitted,
    /// `Error.kind.invalid`.
    Invalid,
    /// `Error.kind.limit`.
    Limit,
    /// `Error.kind.revoked`.
    Revoked,
    /// `Error.kind.unavailable`.
    Unavailable,
    /// `Error.kind.other`, or an `Error.kind` variant newer than this build.
    Other,
    /// The handler returned a `capnp::Error` (not a typed `Error`).
    Failed,
    /// The connection dropped under the call.
    Disconnected,
    /// The method has no handler implementation (a client ahead of the server).
    Unimplemented,
    /// The caller dropped the call before it completed.
    Cancelled,
}

impl Outcome {
    pub const ALL: [Outcome; 12] = [
        Outcome::Ok,
        Outcome::NotFound,
        Outcome::NotPermitted,
        Outcome::Invalid,
        Outcome::Limit,
        Outcome::Revoked,
        Outcome::Unavailable,
        Outcome::Other,
        Outcome::Failed,
        Outcome::Disconnected,
        Outcome::Unimplemented,
        Outcome::Cancelled,
    ];

    pub fn label(self) -> &'static str {
        match self {
            Outcome::Ok => "ok",
            Outcome::NotFound => "not_found",
            Outcome::NotPermitted => "not_permitted",
            Outcome::Invalid => "invalid",
            Outcome::Limit => "limit",
            Outcome::Revoked => "revoked",
            Outcome::Unavailable => "unavailable",
            Outcome::Other => "other",
            Outcome::Failed => "failed",
            Outcome::Disconnected => "disconnected",
            Outcome::Unimplemented => "unimplemented",
            Outcome::Cancelled => "cancelled",
        }
    }

    /// Maps an `Error.kind` union member, by schema name, to its outcome.
    /// `None` for a member this build does not know.
    pub fn from_error_kind(name: &str) -> Option<Outcome> {
        Some(match name {
            "notFound" => Outcome::NotFound,
            "notPermitted" => Outcome::NotPermitted,
            "invalid" => Outcome::Invalid,
            "limit" => Outcome::Limit,
            "revoked" => Outcome::Revoked,
            "unavailable" => Outcome::Unavailable,
            "other" => Outcome::Other,
            _ => return None,
        })
    }

    pub fn from_capnp(err: &capnp::Error) -> Outcome {
        match err.kind {
            capnp::ErrorKind::Disconnected => Outcome::Disconnected,
            capnp::ErrorKind::Unimplemented => Outcome::Unimplemented,
            _ => Outcome::Failed,
        }
    }
}
